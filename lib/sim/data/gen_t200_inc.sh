# Regenerates t200_thrust.inc (the C table sim_thrust.c includes) from
# t200_thrust.csv. The .inc is checked in so a build needs nothing but a C
# compiler; run this after changing the CSV, and the sim test suite checks
# that the two still agree (test_t200_inc_matches_csv).
#
# Usage: sh lib/sim/data/gen_t200_inc.sh > lib/sim/data/t200_thrust.inc
# Conversion: kilogram-force (as published) to newtons with g_n = 9.80665.
set -e
dir=$(dirname "$0")
awk -F, '
/^#/ { next }
$1 == "pwm_us" {
  nv = NF - 1
  printf "/* Generated by gen_t200_inc.sh from t200_thrust.csv; do not edit. */\n"
  printf "/* Thrust in newtons (kgf * 9.80665), one row per PWM from %s", "1100"
  printf " to 1900 us in 4 us steps, */\n/* one column per voltage: "
  for (i = 2; i <= NF; i++) { v = $i; sub(/^kgf_/, "", v); sub(/V$/, "", v); vs[i] = v; printf "%s%s V", (i > 2 ? ", " : ""), v }
  printf ". */\n"
  printf "static const double sim_t200_volt_table[SIM_T200_NVOLT] = {"
  for (i = 2; i <= NF; i++) printf "%s%s.0", (i > 2 ? ", " : ""), vs[i]
  printf "};\n"
  printf "static const double sim_t200_newton_table[SIM_T200_NROW][SIM_T200_NVOLT] = {\n"
  next
}
NF > 1 {
  n++
  printf "  {"
  for (i = 2; i <= NF; i++) printf "%s%.9g", (i > 2 ? ", " : ""), $i * 9.80665
  printf "}, /* %s */\n", $1
}
END {
  printf "};\n"
  if (n != 201) { print "expected 201 rows, got " n > "/dev/stderr"; exit 1 }
}' "$dir/t200_thrust.csv"
